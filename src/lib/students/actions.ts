"use server";

import { refresh } from "next/cache";
import { z } from "zod";

import { getCurrentUser } from "@/lib/auth";
import { createClient } from "@/lib/supabase/server";
import {
  studentFormSchema,
  type StudentErrorKey,
  type StudentResult,
} from "@/lib/validation/students";

const DENIED = "42501";
const NOT_FOUND = "P0002";
const RULE = "P0001";

async function session() {
  const [supabase, user] = await Promise.all([createClient(), getCurrentUser()]);
  return supabase && user ? { supabase, user } : null;
}

function firstIssue(error: z.ZodError): StudentErrorKey {
  return (error.issues[0]?.message as StudentErrorKey) ?? "generic";
}

function failure(error: { code?: string } | null): { ok: false; error: StudentErrorKey } {
  if (error?.code === DENIED) return { ok: false, error: "notAllowed" };
  if (error?.code === NOT_FOUND) return { ok: false, error: "notFound" };
  if (error?.code === RULE) return { ok: false, error: "leadNotOpen" };
  return { ok: false, error: "generic" };
}

/** The Telegram link code is generated by the database on insert. */
export async function createStudent(input: unknown): Promise<StudentResult<{ id: string }>> {
  const parsed = studentFormSchema.safeParse(input);
  if (!parsed.success) return { ok: false, error: firstIssue(parsed.error) };
  const ctx = await session();
  if (!ctx) return { ok: false, error: "notAllowed" };

  const { data, error } = await ctx.supabase
    .from("students")
    .insert(parsed.data)
    .select("id")
    .single();
  if (error) return failure(error);

  refresh();
  return { ok: true, data: { id: data.id } };
}

export async function updateStudent(id: unknown, input: unknown): Promise<StudentResult> {
  const studentId = z.uuid().safeParse(id);
  const parsed = studentFormSchema.safeParse(input);
  if (!studentId.success) return { ok: false, error: "notFound" };
  if (!parsed.success) return { ok: false, error: firstIssue(parsed.error) };
  const ctx = await session();
  if (!ctx) return { ok: false, error: "notAllowed" };

  const { data, error } = await ctx.supabase
    .from("students")
    .update(parsed.data)
    .eq("id", studentId.data)
    .is("archived_at", null)
    .select("id");
  if (error) return failure(error);
  if (data.length === 0) return { ok: false, error: "notFound" };

  refresh();
  return { ok: true };
}

/**
 * Convert to student: creates the student from the lead, links both ways and
 * marks the lead Won, in one database transaction.
 */
export async function convertLead(
  leadIdInput: unknown,
  input: unknown,
): Promise<StudentResult<{ id: string }>> {
  const leadId = z.uuid().safeParse(leadIdInput);
  const parsed = studentFormSchema.safeParse(input);
  if (!leadId.success) return { ok: false, error: "notFound" };
  if (!parsed.success) return { ok: false, error: firstIssue(parsed.error) };
  const ctx = await session();
  if (!ctx) return { ok: false, error: "notAllowed" };

  const { data, error } = await ctx.supabase.rpc("convert_lead_to_student", {
    p_lead_id: leadId.data,
    p_full_name: parsed.data.full_name,
    p_phone: parsed.data.phone,
    p_parent_name: parsed.data.parent_name ?? undefined,
    p_parent_phone: parsed.data.parent_phone ?? undefined,
    p_birth_date: parsed.data.birth_date ?? undefined,
    p_language: parsed.data.language,
    p_notes: parsed.data.notes ?? undefined,
  });
  if (error) return failure(error);

  refresh();
  return { ok: true, data: { id: data } };
}

/** Pause, and back to active. Paused students are not billed. */
export async function setStudentStatus(id: unknown, status: unknown): Promise<StudentResult> {
  const studentId = z.uuid().safeParse(id);
  const next = z.enum(["active", "paused"]).safeParse(status);
  if (!studentId.success || !next.success) return { ok: false, error: "notFound" };
  const ctx = await session();
  if (!ctx) return { ok: false, error: "notAllowed" };

  const { data, error } = await ctx.supabase
    .from("students")
    .update({ status: next.data })
    .eq("id", studentId.data)
    .is("archived_at", null)
    .select("id");
  if (error) return failure(error);
  if (data.length === 0) return { ok: false, error: "notFound" };

  refresh();
  return { ok: true };
}

/** Mark as left: also ends every active enrolment today, so billing stops. */
export async function markStudentLeft(id: unknown): Promise<StudentResult> {
  const studentId = z.uuid().safeParse(id);
  if (!studentId.success) return { ok: false, error: "notFound" };
  const ctx = await session();
  if (!ctx) return { ok: false, error: "notAllowed" };

  const { error } = await ctx.supabase.rpc("mark_student_left", { p_student_id: studentId.data });
  if (error) return failure(error);

  refresh();
  return { ok: true };
}

/** Owner only: the database refuses anyone else. */
export async function archiveStudent(id: unknown): Promise<StudentResult> {
  const studentId = z.uuid().safeParse(id);
  if (!studentId.success) return { ok: false, error: "notFound" };
  const ctx = await session();
  if (!ctx || ctx.user.role !== "owner") return { ok: false, error: "notAllowed" };

  const { error } = await ctx.supabase
    .from("students")
    .update({ archived_at: new Date().toISOString() })
    .eq("id", studentId.data);
  if (error) return failure(error);

  refresh();
  return { ok: true };
}
