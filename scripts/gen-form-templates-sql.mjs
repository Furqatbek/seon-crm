#!/usr/bin/env node
// Prints the SQL that seeds and publishes the three starting forms, from
// src/lib/forms/templates.ts. Its output was saved as the migration
// supabase/migrations/20261127100200_lead_form_templates.sql.
//
//   node scripts/gen-form-templates-sql.mjs > supabase/migrations/<new file>.sql
//
// Needs Node 22.18 or newer (it loads the TypeScript modules directly).

const { formDocumentSchema } = await import("../src/lib/forms/document.ts");
const { FORM_TEMPLATES } = await import("../src/lib/forms/templates.ts");

const quote = (value) => `'${value.replace(/'/g, "''")}'`;

let sql = `-- The three starting forms, published so they can be opened and tested before
-- the editor exists. docs/SPEC.md → "Lead forms add-on → Form builder".
-- Generated by scripts/gen-form-templates-sql.mjs from src/lib/forms/templates.ts.
-- A slug already in use is left alone.
`;

for (const template of FORM_TEMPLATES) {
  const document = JSON.stringify(formDocumentSchema.parse(template.document), null, 2);
  sql += `
with form as (
  insert into public.lead_forms (name, slug, status, source_tag, draft, published, published_version, published_at, created_by, updated_by)
  select ${quote(template.name)}, ${quote(template.slug)}, 'live', ${quote(template.source_tag)}, d.doc, d.doc, 1, now(), null, null
  from (select $form$${document}$form$::jsonb as doc) d
  on conflict (slug) do nothing
  returning id, published
)
insert into public.lead_form_versions (form_id, version, content, published_by)
select form.id, 1, form.published, null from form;
`;
}

process.stdout.write(sql);
